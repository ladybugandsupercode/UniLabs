/* Вариант 3.2
Дано натуральное число N (N<10^9).
Найти сумму четных цифр числа N.
*/

#include <iostream>
#ifdef _WIN32 // _WIN32 = «мы на Windows»; на других системах этот кусок пропустится
#include <windows.h> // нужен для настройки кодировки консоли
#endif
using namespace std;

int main() {

    #ifdef _WIN32
        SetConsoleOutputCP(CP_UTF8); // чтобы русский текст не превратился в кракозябры
        SetConsoleCP(CP_UTF8);
    #endif


    int N; // N < 10^9 = 1 000 000 000, это помещается в int (его предел около 2,1 миллиарда)

    cout << "Введите натуральное число N (меньше 1000000000): ";
    cin >> N;



    // в C++ запись 10^9 не степень (^ это побитовое XOR), поэтому пишем число целиком
    if (cin.fail() || N <= 0 || N >= 1000000000) {
        cout << "Ошибка: N должно быть натуральным числом меньше 10^9" << endl;
        return 1;
    }



    int sum = 0;    // сумма чётных цифр; начинаем с 0, потому что 0 не влияет на сложение
    int newN = N;   // рабочая копия: цикл будет «съедать» число, а N нам ещё нужно целым

    while (newN > 0) { // пока в числе остались цифры
        int digit = newN % 10; // последняя цифра числа

        if (digit % 2 == 0) { // чётная цифра (в том числе 0, он ничего не добавит)
            sum += digit; // sum += digit — то же, что sum = sum + digit
        }

        newN /= 10; // отбрасываем последнюю цифру: 4825 -> 482
    }

    cout << "Сумма чётных цифр числа " << N << ": " << sum << endl;

    return 0;
}


