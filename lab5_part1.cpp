/* Вариант 3.1
Дана последовательность целых чисел {Aj}.
Найти произведение чисел, лежащих на отрезке [-2,20],
наименьшее из таких чисел и номер этого числа в последовательности.
*/

#include <iostream>
#ifdef _WIN32 // _WIN32 = «мы на Windows»; на других системах этот кусок пропустится
#include <windows.h> // нужен для настройки кодировки консоли
#endif
using namespace std;

int main() {
    #ifdef _WIN32
        SetConsoleOutputCP(CP_UTF8); // чтобы русский текст не превратился в кракозябры
        SetConsoleCP(CP_UTF8);
    #endif

    int n;

    cout << "Введите количество чисел n: ";
    cin >> n;


    if (cin.fail() || n <= 0) { // ввели не число или последовательность пустая
        cout << "Ошибка: n должно быть натуральным числом" << endl;
        return 1;
    }


    long long product = 1; // 1 — нейтральный элемент умножения; long long, чтобы произведение не переполнилось
    int minValue = 0;      // наименьшее из подходящих чисел (значение пока не важно)
    int minIndex = 0;      // его номер в последовательности
    bool found = false;    // нашли ли хоть одно число из отрезка [-2, 20]


    cout << "Введите " << n << " целых чисел: ";



    for (int j = 1; j <= n; j++) { // старт с j == 1, условие продолжения, после каждой итерации j +1
        int a = 0;
        cin >> a;

        if (cin.fail()) {
            cout << "Ошибка: нужно вводить целые числа" << endl;
            return 1;
        }


        if (a >= -2 && a <= 20) {
            product *= a; // накапливаем произведение

            if (found == false || a < minValue) { // первое подходящее или новый рекорд
                // ещё ничего не нашли или это число меньше текущего рекордсмена
                minValue = a;
                minIndex = j;
                found = true;
            }
        }  
        }




    if (found) {
        cout << "Произведение: " << product << endl;
        cout << "Наименьшее: " << minValue << endl;
        cout << "Номер наименьшего: " << minIndex << endl;
    }
    else { // подходящих чисел не было
        cout << "В последовательности нет чисел из отрезка [-2, 20]" << endl;
    }

    return 0;
}

