/* Вариант 3.1
Ввести натуральные числа A, B и C.
Если A больше B и B больше C,то вывести A-B-C,
если B больше A и B  кратно C, то вывести B/С+B-A,
в остальных случаях вывести A+B+C.
*/

#include <iostream>
using namespace std;

int main() {
    int A, B, C; // int, а не unsigned: разность A - B - C может получиться отрицательной

    cout << "Введите значения ля переменных A, B, и C: ";
    cin >> A >> B >> C;

    if (A > B && B > C) { // оба условия должны выполниться одновременно
    }

    else if (B > A && B % C == 0) { // B кратно C => B делится на C без остатка
        cout << B / C + B - A << endl;
    }

    else { // все остальные случаи, в том числе когда числа равны
        cout << A + B + C << endl;
    }
    
    return 0;
}