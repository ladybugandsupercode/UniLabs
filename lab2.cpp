// Вариант 3.
// Написать программу, которая, используя минимальное количество оперативной памяти рассчитает, 
// периметр прямоугольника со сторонами A и B (0 < A,B < 20). A и B считать с клавиатуры.


#include <iostream>                 // input output stream

int main() {                        // int значит, что в конце она вернёт целое число
    float a, b;                     // float = floating point, число с дробной частью; занимает 4 байта, поэтому a и b вместе 8 байт; это самый маленький дробный тип
    std::cin >> a >> b;

    std::cout << 2 * (a + b);       // console output; << «выведи на экран»; выводим периметр 2 * (A + B); отдельную переменную под ответ не заводим, чтобы не тратить память

    return 0;                       // возвращаем 0, что значит «программа завершилась без ошибок»
}


// для примера возьмём A = 2.5, B = 4:  периметр = 2 * (2.5 + 4) = 13
















